import math

print("Square root of 16 is :",math.sqrt(16))
print("Value of pi is :",math.pi)
print("Value of e is :",math.e)
print("Factorial of 5 is :",math.factorial(5))
print("2 to the power 3 is :",math.pow(2,3))
print("Logarithm of 100 with base 10 is :",math.log10(100))
print("Logarithm of 100 with base e is :",math.log(100))
print("Sine value of 90 degree is :",math.sin(math.radians(90)))
print("Cosine value of 0 degree is :",math.cos(math.radians(0)))
