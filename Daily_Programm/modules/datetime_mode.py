import datetime

x = datetime.datetime.now() # current date and time
print(x)

print(x.year)
print("date :",x.date())
print("time :",x.time())
print("month :",x.month)
print("day :",x.day)
print("hour :",x.hour)
print("minute :",x.minute)
print("second :",x.second)
print("microsecond :",x.microsecond)
print("weekday :",x.weekday()) # Monday is 0 and Sunday is 6